import { execFileSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const rust = '1.98.1';
const bindgen = '0.2.126';
const manifest = 'src/wasm/policy/Cargo.toml';
const generated = 'src/wasm/generated';
function run(command, args, capture = false) {
  return execFileSync(command, args, { cwd: root, stdio: capture ? 'pipe' : 'inherit', encoding: 'utf8',
    env: { ...process.env, CARGO_HTTP_USER_AGENT: 'codex' } });
}
if (!run('rustc', [`+${rust}`, '--version'], true).startsWith(`rustc ${rust} `)) throw new Error('Rust pin mismatch');
if (run('wasm-bindgen', ['--version'], true).trim() !== `wasm-bindgen ${bindgen}`) throw new Error('wasm-bindgen pin mismatch');
run('cargo', [`+${rust}`, 'fmt', '--manifest-path', manifest, '--check']);
run('cargo', [`+${rust}`, 'test', '--locked', '--manifest-path', manifest]);
run('cargo', [`+${rust}`, 'build', '--locked', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', manifest]);
await mkdir(new URL(`../${generated}/`, import.meta.url), { recursive: true });
run('wasm-bindgen', ['--target', 'web', '--out-dir', generated, '--out-name', 'policy',
  'src/wasm/policy/target/wasm32-unknown-unknown/release/studio_policy.wasm']);
// Keep the pinned bindgen glue's synchronous path only: the unused URL/fetch
// initializer must not be shipped, regardless of bundler tree shaking.
const bindingPath = new URL(`../${generated}/policy.js`, import.meta.url);
const binding = await readFile(bindingPath, 'utf8');
const load = binding.indexOf('async function __wbg_load(');
const sync = binding.indexOf('function initSync(');
const asyncInit = binding.indexOf('async function __wbg_init(');
if (load < 0 || sync <= load || asyncInit <= sync || !binding.includes('export { initSync, __wbg_init as default };'))
  throw new Error('Unexpected pinned wasm-bindgen glue shape');
const syncOnly = binding.slice(0, load) + binding.slice(sync, asyncInit) + 'export { initSync };\n';
if (/\bfetch\s*\(|new URL\(/.test(syncOnly)) throw new Error('URL loader remains in policy glue');
await writeFile(bindingPath, syncOnly);
const wasm = await readFile(new URL(`../${generated}/policy_bg.wasm`, import.meta.url));
await writeFile(new URL(`../${generated}/policy-bytes.ts`, import.meta.url),
  `// Generated by build:wasm. No URL initializer is used.\nexport const policyBytes = '${wasm.toString('base64')}';\n`);
console.log('Pinned dekopon-policy wasm built; runtime bytes are embedded in JavaScript');
